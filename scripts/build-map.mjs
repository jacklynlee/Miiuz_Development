/* Builds js/data/malaysia.map.js: a small, offline outline map of Malaysia and its
 * neighbours (Natural Earth 1:10m, public domain) for the app's overview and locator maps.
 * Run once after changing the extent or size:
 *   npm i --no-save world-atlas@2.0.2 topojson-client@3.1.0 d3-geo@3.1.1 && node scripts/build-map.mjs */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(process.cwd(), "x.js"));
const { feature } = require("topojson-client");
const d3 = await import(require.resolve("d3-geo"));

// East Malaysia is drawn 3° of longitude further west than it really is, so both halves of
// the country fit a phone screen; a dashed line marks the break (a standard inset).
const SPLIT = 106.5, SHIFT = 3;
const W = 1000, H = 412;
const world = JSON.parse(readFileSync(require.resolve("world-atlas/countries-10m.json"), "utf8"));
const countries = feature(world, world.objects.countries).features;
const MALAYSIA = "458", NEIGHBOURS = ["764", "360", "702", "096", "608"]; // Thailand, Indonesia, Singapore, Brunei, Philippines

const extent = { type: "Feature", geometry: { type: "MultiPoint", coordinates: [[99.3, 0.7], [119.5 - SHIFT, 7.6]] } };
const west = d3.geoMercator().fitExtent([[8, 8], [W - 8, H - 8]], extent);
const k = west.scale(), [tx, ty] = west.translate();
const cut = west([SPLIT - SHIFT / 2, 0])[0];
west.clipExtent([[0, 0], [cut, H]]);
const east = d3.geoMercator().scale(k).translate([tx - k * SHIFT * Math.PI / 180, ty]).clipExtent([[cut, 0], [W, H]]);

const my = countries.find(f => f.id === MALAYSIA);
const near = { type: "FeatureCollection", features: countries.filter(f => NEIGHBOURS.includes(f.id)) };
const both = f => d3.geoPath(west).digits(0)(f) + d3.geoPath(east).digits(0)(f);

const out = `/* Generated by scripts/build-map.mjs — outline of Malaysia and its neighbours from
 * Natural Earth (public domain), Mercator projection. Do not edit by hand. */
(function (root) {
  const MAP = {
    w: ${W}, h: ${H},
    land: ${JSON.stringify(both(my))},
    near: ${JSON.stringify(both(near))},
    // Mercator: x = k·λ + tx, y = ty − k·ln(tan(π/4 + φ/2)), λ/φ in radians;
    // east of \`split\` longitude, λ is reduced by \`shift\` degrees. \`cut\` is the inset line.
    k: ${k.toFixed(4)}, tx: ${tx.toFixed(4)}, ty: ${ty.toFixed(4)}, split: ${SPLIT}, shift: ${SHIFT}, cut: ${cut.toFixed(1)},
  };
  if (typeof module === "object" && module.exports) module.exports = MAP;
  else { root.MBB = root.MBB || {}; root.MBB.mapData = MAP; }
})(typeof window !== "undefined" ? window : globalThis);
`;
writeFileSync(path.join(root, "js/data/malaysia.map.js"), out);
console.log(`js/data/malaysia.map.js: ${(out.length / 1024).toFixed(1)} KB`);
