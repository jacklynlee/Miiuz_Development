#!/usr/bin/env node
/* Miiuz Beyond Borders — copy third-party browser files into the repo, so the app never
 * depends on a CDN (jsDelivr and Google Fonts are blocked or unreliable in mainland China, #18).
 *
 *   npm run vendor
 *
 * Downloads each pinned package from the npm registry (npm checks its integrity), copies only
 * the files the app loads into vendor/ and fonts/, and writes css/fonts.css. Commit the result.
 * To upgrade a package: change its version below, run this, update the paths in js/maps.js,
 * js/member.js and sw.js if the folder name changed, then test maps, sign-in and fonts. */
import { execFileSync } from "node:child_process";
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const SCRIPTS = [
  { pkg: "maplibre-gl", version: "5.24.0", files: ["dist/maplibre-gl.js", "dist/maplibre-gl.css", "LICENSE.txt"] },
  { pkg: "@supabase/supabase-js", version: "2.117.3", files: ["dist/umd/supabase.js", "LICENSE"] },
];
// Latin fonts only. Chinese, Japanese and Korean text uses the phone's own fonts (PingFang,
// Noto Sans CJK, Microsoft YaHei, Hiragino, Apple SD Gothic Neo…), which are already installed.
const FONTS = [
  { pkg: "@fontsource/noto-sans", version: "5.3.0", family: "Noto Sans", weights: [400, 500, 700] },
  { pkg: "@fontsource/noto-serif", version: "5.3.0", family: "Noto Serif", weights: [600, 900] },
  { pkg: "@fontsource/ibm-plex-mono", version: "5.3.0", family: "IBM Plex Mono", weights: [500, 600] },
];
// Scripts of the app's languages that these fonts cover. Browsers download a file only when the page uses it.
const SUBSETS = ["latin", "latin-ext", "vietnamese", "cyrillic", "greek"];

function unpack(pkg, version) {
  const dir = mkdtempSync(path.join(tmpdir(), "mbb-vendor-"));
  const tgz = execFileSync("npm", ["pack", `${pkg}@${version}`, "--silent", "--pack-destination", dir], { encoding: "utf8" }).trim().split("\n").pop();
  execFileSync("tar", ["-xzf", path.join(dir, tgz), "-C", dir]);
  return { dir, pkgDir: path.join(dir, "package") };
}

for (const s of SCRIPTS) {
  const { dir, pkgDir } = unpack(s.pkg, s.version);
  const dest = path.join(root, "vendor", `${s.pkg.split("/").pop()}@${s.version}`);
  rmSync(dest, { recursive: true, force: true });
  mkdirSync(dest, { recursive: true });
  for (const f of s.files) cpSync(path.join(pkgDir, f), path.join(dest, path.basename(f)));
  rmSync(dir, { recursive: true, force: true });
  console.log(`vendor/${path.basename(dest)}: ${s.files.map(f => path.basename(f)).join(", ")}`);
}

const fontsDir = path.join(root, "fonts");
rmSync(fontsDir, { recursive: true, force: true });
mkdirSync(fontsDir, { recursive: true });
let css = `/* Generated by scripts/vendor.mjs: do not edit by hand.
 * Latin web fonts, served from this site (SIL Open Font License 1.1, see fonts/LICENSE-*.txt).
 * unicode-range keeps each file to the characters it covers, so CJK text falls through to the
 * phone's own fonts and nothing is downloaded for it. font-display: swap never blocks text. */
`;
for (const f of FONTS) {
  const { dir, pkgDir } = unpack(f.pkg, f.version);
  const id = f.pkg.split("/").pop();
  for (const w of f.weights) {
    const src = readFileSync(path.join(pkgDir, `${w}.css`), "utf8");
    for (const sub of SUBSETS) {
      const file = `${id}-${sub}-${w}-normal.woff2`;
      // Pick this subset's @font-face block and its unicode-range from the package's CSS.
      const block = src.split("@font-face").find(b => b.includes(`/${file}`));
      const range = block?.match(/unicode-range:\s*([^;]+);/)?.[1];
      if (!range || !existsSync(path.join(pkgDir, "files", file))) {
        if (sub === "latin") throw new Error(`${f.pkg}: no ${file}`);
        continue; // this family doesn't cover that script; the phone's font is used
      }
      cpSync(path.join(pkgDir, "files", file), path.join(fontsDir, file));
      css += `@font-face { font-family: "${f.family}"; font-style: normal; font-weight: ${w}; font-display: swap; src: url("../fonts/${file}") format("woff2"); unicode-range: ${range.trim()}; }\n`;
    }
  }
  const lic = ["LICENSE", "LICENSE.md", "OFL.txt"].find(n => existsSync(path.join(pkgDir, n)));
  if (lic) cpSync(path.join(pkgDir, lic), path.join(fontsDir, `LICENSE-${id}.txt`));
  rmSync(dir, { recursive: true, force: true });
  console.log(`fonts/${id}: ${f.weights.join(", ")} × ${SUBSETS.join(", ")}`);
}
writeFileSync(path.join(root, "css", "fonts.css"), css);
console.log("css/fonts.css written");
